import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile, copyFile, lstat, realpath, rm, cp } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "dist");
const source = path.join(root, "miniapp/static");
const types = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png",
};
const manifest = JSON.parse(await readFile(path.join(root, ".openai/hosting.json"), "utf8"));
if (!manifest.project_id || manifest.static != null) throw new Error("A registered Worker hosting manifest without static is required");
if (manifest.r2 !== "BUCKET") throw new Error("Declare r2: BUCKET in .openai/hosting.json for original note images");
const assets = Object.create(null);
for (const entry of await readdir(source, { withFileTypes: true })) {
  if (!entry.isFile()) throw new Error(`Unexpected static directory: ${entry.name}`);
  const extension = path.extname(entry.name);
  if (!Object.hasOwn(types, extension)) throw new Error(`Unsupported static asset: ${entry.name}`);
  const bytes = await readFile(path.join(source, entry.name));
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  assets[entry.name] = { type: types[extension], size: bytes.length, sha256 };
  if (extension === ".png") assets[entry.name].key = `miniapp-assets/${sha256}/${entry.name}`;
  else assets[entry.name].text = bytes.toString("utf8");
}

function enclosedModule(text, names) {
  if (/^\s*import\b/m.test(text) || /^\s*export\s+(?:default|\*)/m.test(text)) {
    throw new Error("Cloud build modules must be self-contained and use named declaration exports");
  }
  const body = text.replace(/^export\s+(?=(?:async\s+)?function\b|(?:const|let|class)\b)/gm, "");
  return `(() => {\n${body}\nreturn { ${names.join(", ")} };\n})()`;
}
const catalogue = JSON.parse(await readFile(path.join(root, "cloud/catalogue.json"), "utf8"));
const assetCode = await readFile(path.join(root, "cloud/worker/assets.mjs"), "utf8");
const backendCode = await readFile(path.join(root, "cloud/worker/backend.mjs"), "utf8");
const bundle = `// Generated by cloud/build.mjs from the existing Mini App source. Do not edit.\n` +
  `const ASSETS = ${JSON.stringify(assets)};\nconst CATALOGUE = ${JSON.stringify(catalogue)};\n` +
  `const assetRuntime = ${enclosedModule(assetCode, ["serveAsset", "bootstrapAsset", "secureResponse"])};\n` +
  `const backend = ${enclosedModule(backendCode, ["handleApi"])};\n` +
  `export default { async fetch(request, env, ctx) {\n` +
  `  let response;\n  try {\n` +
  `    response = await assetRuntime.bootstrapAsset(request, env, ASSETS)\n` +
  `      || await backend.handleApi(request, env, CATALOGUE)\n` +
  `      || await assetRuntime.serveAsset(request, env, ASSETS)\n` +
  `      || new Response("Not found", {status:404});\n` +
  `  } catch (error) {\n    console.error("Worker failure", error?.name || "Error");\n` +
  `    response = Response.json({error:"temporarily_unavailable"}, {status:503});\n  }\n` +
  `  return assetRuntime.secureResponse(response, request);\n} };\n`;
const compressedBytes = gzipSync(bundle).byteLength;
if (compressedBytes > 3 * 1024 * 1024) throw new Error(`Worker exceeds free 3 MiB compressed limit: ${compressedBytes}`);
// Parse the exact artifact before replacing a previous successful build.
const built = await import(`data:text/javascript;base64,${Buffer.from(bundle).toString("base64")}`);
if (typeof built.default?.fetch !== "function") throw new Error("Worker default.fetch is missing");
const previous = await lstat(output).catch(error => { if (error.code === "ENOENT") return null; throw error; });
if (previous) {
  if (!previous.isDirectory() || previous.isSymbolicLink()
      || path.relative(await realpath(root), await realpath(output)) !== "dist") {
    throw new Error("Refusing to replace a build directory outside the checkout");
  }
  await rm(output, { recursive: true });
}
await mkdir(path.join(output, "server"), { recursive: true });
await mkdir(path.join(output, ".openai"), { recursive: true });
await writeFile(path.join(output, "server/index.js"), bundle);
await copyFile(path.join(root, ".openai/hosting.json"), path.join(output, ".openai/hosting.json"));
// Keep one canonical SQL source in cloud/migrations. Sites consumes Drizzle's
// journal and the matching SQL filename from its deployment metadata directory.
await mkdir(path.join(output, ".openai/drizzle"), { recursive: true });
await cp(path.join(root, "cloud/drizzle/meta"), path.join(output, ".openai/drizzle/meta"), { recursive: true });
await copyFile(path.join(root, "cloud/migrations/0001_private_state.sql"), path.join(output, ".openai/drizzle/0000_private_state.sql"));
console.log(`Built dist/server/index.js: ${Buffer.byteLength(bundle)} bytes, gzip ${compressedBytes} bytes`);
for (const [name, asset] of Object.entries(assets)) {
  if (asset.key) console.log(`Initialize R2: ${name} (${asset.size} bytes, sha256 ${asset.sha256})`);
}
